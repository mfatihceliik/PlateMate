UPDATE plate_report_type_translations
SET label = CASE pt.code
        WHEN 'POLITE'                 THEN 'Polite'
        WHEN 'GAVE_WAY'              THEN 'Gave Way'
        WHEN 'RESPECTFUL'            THEN 'Respectful'
        WHEN 'THANKED'               THEN 'Thanked'
        WHEN 'PATIENT'               THEN 'Patient'
        WHEN 'CAREFUL'               THEN 'Careful'
        WHEN 'SAFE_DRIVING'          THEN 'Safe Driving'
        WHEN 'SPEEDING'              THEN 'Speeding'
        WHEN 'AGGRESSIVE'            THEN 'Aggressive Driver'
        WHEN 'TAILGATING'            THEN 'Tailgating'
        WHEN 'NO_SIGNAL'             THEN 'No Signal'
        WHEN 'HONKER'                THEN 'Honker'
        WHEN 'UNSAFE_LANE_CHANGE'    THEN 'Unsafe Lane Change'
        WHEN 'SPEEDING_REPORT'       THEN 'Speeding Report'
        WHEN 'PARKING_ISSUE'         THEN 'Parking Issue'
        WHEN 'HONKING_DISTURBANCE'   THEN 'Honking Disturbance'
        WHEN 'TRAFFIC_RULE_VIOLATION' THEN 'Traffic Rule Violation'
        WHEN 'POSITIVE_DRIVER'       THEN 'Positive Driver'
        WHEN 'HELPFUL_DRIVER'        THEN 'Helpful Driver'
        WHEN 'RESPECTFUL_DRIVER'     THEN 'Respectful Driver'
        WHEN 'THANK_YOU_REPORT'      THEN 'Thank You Report'
        WHEN 'RED_LIGHT_VIOLATION'   THEN 'Red Light Violation'
        WHEN 'WRONG_WAY'             THEN 'Wrong Way'
        WHEN 'PHONE_USAGE'           THEN 'Phone Usage'
        WHEN 'ILLEGAL_PARKING'       THEN 'Illegal Parking'
        ELSE plate_report_type_translations.label
    END,
    description = CASE pt.code
        WHEN 'POLITE'                 THEN 'Polite and proper behavior report.'
        WHEN 'GAVE_WAY'              THEN 'Gave way behavior report.'
        WHEN 'RESPECTFUL'            THEN 'Respectful driver behavior report.'
        WHEN 'THANKED'               THEN 'Driver who thanked report.'
        WHEN 'PATIENT'               THEN 'Patient driver behavior report.'
        WHEN 'CAREFUL'               THEN 'Careful driving behavior report.'
        WHEN 'SAFE_DRIVING'          THEN 'Safe driving behavior report.'
        WHEN 'SPEEDING'              THEN 'Speeding behavior report.'
        WHEN 'AGGRESSIVE'            THEN 'Aggressive driving behavior report.'
        WHEN 'TAILGATING'            THEN 'Tailgating violation report.'
        WHEN 'NO_SIGNAL'             THEN 'Maneuvering without signaling report.'
        WHEN 'HONKER'                THEN 'Excessive honking report.'
        WHEN 'UNSAFE_LANE_CHANGE'    THEN 'Dangerous or sudden lane change behavior report.'
        WHEN 'SPEEDING_REPORT'       THEN 'Potential speeding violation report.'
        WHEN 'PARKING_ISSUE'         THEN 'Parking behavior affecting traffic flow report.'
        WHEN 'HONKING_DISTURBANCE'   THEN 'Excessive honking disturbance report.'
        WHEN 'TRAFFIC_RULE_VIOLATION' THEN 'Traffic rule violation behavior report.'
        WHEN 'POSITIVE_DRIVER'       THEN 'Positive and considerate driving behavior report.'
        WHEN 'HELPFUL_DRIVER'        THEN 'Helpful behavior in traffic report.'
        WHEN 'RESPECTFUL_DRIVER'     THEN 'Respectful and safe behavior report.'
        WHEN 'THANK_YOU_REPORT'      THEN 'General appreciation report.'
        WHEN 'RED_LIGHT_VIOLATION'   THEN 'Red light violation report.'
        WHEN 'WRONG_WAY'             THEN 'Driving in the wrong direction report.'
        WHEN 'PHONE_USAGE'           THEN 'Using phone while driving report.'
        WHEN 'ILLEGAL_PARKING'       THEN 'Illegal parking report.'
        ELSE plate_report_type_translations.description
    END
FROM plate_report_types pt
WHERE plate_report_type_translations.report_type_id = pt.id
  AND plate_report_type_translations.locale = 'en';
